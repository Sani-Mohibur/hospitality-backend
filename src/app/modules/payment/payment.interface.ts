import { Types } from 'mongoose';

export const PAYMENT_METHOD = {
  CASH: 'CASH',
  // Card through Stripe (online / Elements) on the tenant's connected account
  CARD_ONLINE: 'CARD_ONLINE',
  // Card-present through Stripe Terminal
  CARD_TERMINAL: 'CARD_TERMINAL',
  // Card taken on a standalone bank terminal; recorded only
  CARD_EXTERNAL: 'CARD_EXTERNAL',
  BANK_TRANSFER: 'BANK_TRANSFER',
  CHARGE_TO_ROOM: 'CHARGE_TO_ROOM',
  CITY_LEDGER: 'CITY_LEDGER',
  VOUCHER: 'VOUCHER',
  LOYALTY: 'LOYALTY',
} as const;

export const PAYMENT_STATUS = {
  PENDING: 'PENDING',
  COMPLETED: 'COMPLETED',
  FAILED: 'FAILED',
  CANCELLED: 'CANCELLED',
  PARTIALLY_REFUNDED: 'PARTIALLY_REFUNDED',
  REFUNDED: 'REFUNDED',
} as const;

export const PAYMENT_TARGET = {
  ORDER: 'ORDER',
  FOLIO: 'FOLIO',
  RETAIL_SALE: 'RETAIL_SALE',
} as const;

export type TPaymentMethod = keyof typeof PAYMENT_METHOD;
export type TPaymentTarget = keyof typeof PAYMENT_TARGET;

export interface IRefund {
  amountMinor: number;
  reason: string;
  at: Date;
  by?: Types.ObjectId;
  approvedBy?: Types.ObjectId;
  providerRef?: string;
  status: 'PENDING' | 'SUCCEEDED' | 'FAILED';
}

export interface IPayment {
  tenantId: Types.ObjectId;
  locationId: Types.ObjectId;
  outletId?: Types.ObjectId;
  target: { kind: TPaymentTarget; id: Types.ObjectId; checkNo?: number };
  method: TPaymentMethod;
  amountMinor: number;
  tipMinor: number;
  tenderedMinor?: number;
  changeMinor?: number;
  currency: string;
  status: keyof typeof PAYMENT_STATUS;
  refundedMinor: number;
  refunds: IRefund[];
  stripe?: {
    accountId?: string;
    paymentIntentId?: string;
    chargeId?: string;
    applicationFeeMinor?: number;
  };
  folioPosting?: { roomStayId?: Types.ObjectId; folioId: Types.ObjectId; roomNumber?: string; guestName?: string; signatureUrl?: string };
  folioLineIds: Types.ObjectId[];
  reference?: string;
  note?: string;
  // Guest whose loyalty points paid (LOYALTY method)
  guestId?: Types.ObjectId;
  shiftId?: Types.ObjectId;
  deviceId?: Types.ObjectId;
  // Id generated by an offline device; unique so a retried sync cannot double-charge
  clientRef?: string;
  offline?: boolean;
  createdBy?: Types.ObjectId;
  completedAt?: Date;
  failureReason?: string;
}
